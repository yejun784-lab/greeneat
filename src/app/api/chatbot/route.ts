/*  매칭 로직                                                            */
/* ------------------------------------------------------------------ */
function normalize(str: string) {
  return str
    .toLowerCase()
    .replace(/[\s\-_]/g, '')       // 공백·하이픈 제거
    .replace(/[?!.~ㅠㅜㅡ]/g, '')  // 감탄사·끝문자 제거
}

function getBotResponse(message: string): string {
  const norm = normalize(message)

  // 1차: 정규화된 메시지로 키워드 매칭
  for (const faq of FAQ) {
    if (faq.keywords.some((kw) => norm.includes(normalize(kw)))) {
      return faq.answer
    }
  }

  // 2차: 원문 부분 포함
  const lower = message.toLowerCase()
  for (const faq of FAQ) {
    if (faq.keywords.some((kw) => lower.includes(kw))) {
      return faq.answer
    }
  }

  return '흠, 제가 아직 배우는 중이라 그 질문은 잘 모르겠어요 🤔\n아래 주제는 바로 답할 수 있어요!\n• 배송 / 배송조회 / 배송비\n• 구독 플랜 / 변경 / 정지\n• 주문취소 / 환불 / 교환\n• 포인트 / 쿠폰 / 결제\n• 영양정보 / 알레르기 / 재입고\n\n더 자세한 문의는 support@greeneat.kr 로 보내주세요 😊'
}

/* ------------------------------------------------------------------ */
/*  핸들러                                                               */
/* ------------------------------------------------------------------ */
export async function POST(req: NextRequest) {
  const { message } = await req.json()
  if (!message?.trim()) {
    return NextResponse.json({ error: '메시지를 입력해주세요.' }, { status: 400 })
  }

  let userName: string | null = null
  try {
    const supabase = await createClient()
    const { data: { user } } = await supabase.auth.getUser()
    if (user) {
      const { data: profile } = await supabase.from('profiles').select('name').eq('id', user.id).single()
      userName = profile?.name ?? null
    }
  } catch {}

  const reply = getBotResponse(message)
  return NextResponse.json({ reply, userName })
}
